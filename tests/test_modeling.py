"""Leave-one-out and repeated cross-validation."""

import numpy as np
import pandas as pd
import pytest
from sklearn.metrics import mean_absolute_error, r2_score

from bioprocess.data import TARGET_COLUMN, load_dataset
from bioprocess.modeling import (
    N_REPEATS,
    N_SPLITS,
    evaluate_models,
    fit_predict_forest,
    fit_predict_mean,
    leave_one_out_predictions,
    quadratic_insample_check,
)
from bioprocess.paths import RESULTS_DIR


@pytest.fixture(scope="module")
def evaluation():
    return evaluate_models(load_dataset())


def _manual_loo_mean(target: pd.Series) -> np.ndarray:
    values = target.to_numpy(dtype=float)
    predictions = np.empty(len(values))
    for index in range(len(values)):
        predictions[index] = np.mean(np.delete(values, index))
    return predictions


def test_mean_baseline_matches_a_hand_calculation():
    dataset = load_dataset()
    predicted = leave_one_out_predictions(dataset, fit_predict_mean)
    expected = _manual_loo_mean(dataset[TARGET_COLUMN])
    np.testing.assert_allclose(predicted, expected)


def test_loo_covers_every_run_and_does_not_copy_the_label(evaluation):
    dataset = load_dataset()
    summary, predictions, repeats = evaluation
    assert list(predictions["run_id"]) == list(dataset["run_id"])
    assert len(predictions) == 29
    # A model that memorises the held-out label would have zero error.
    assert predictions["random_forest"].std(ddof=1) > 0
    observed = predictions["observed_red_pigment_yield_g_l"]
    assert not np.allclose(predictions["mean_baseline"], observed)
    assert set(summary["model"]) == {
        "mean_baseline",
        "linear_regression",
        "quadratic_response_surface",
        "random_forest",
    }
    assert repeats.groupby("model").size().eq(N_REPEATS).all()
    assert summary["n_splits"].eq(N_SPLITS).all()


def test_reported_loo_mae_matches_the_prediction_table(evaluation):
    summary, predictions, _ = evaluation
    observed = predictions["observed_red_pigment_yield_g_l"]
    for _, row in summary.iterrows():
        mae = mean_absolute_error(observed, predictions[row["model"]])
        r2 = r2_score(observed, predictions[row["model"]])
        assert row["loo_mae"] == np.float64(mae) or np.isclose(row["loo_mae"], mae)
        assert np.isclose(row["loo_r2"], r2)


def test_repeated_cv_spread_is_computed_from_the_repeats(evaluation):
    summary, _, repeats = evaluation
    for _, row in summary.iterrows():
        scores = repeats.loc[repeats["model"] == row["model"], "mae"]
        assert np.isclose(row["repeated_cv_mae_mean"], scores.mean())
        assert np.isclose(row["repeated_cv_mae_std"], scores.std(ddof=1))
        assert row["repeated_cv_mae_std"] >= 0


def test_forest_predictions_are_repeatable():
    dataset = load_dataset()
    first = leave_one_out_predictions(dataset, fit_predict_forest)
    second = leave_one_out_predictions(dataset, fit_predict_forest)
    np.testing.assert_allclose(first, second)


def test_committed_metrics_match_a_fresh_run(evaluation):
    """The results table in the repository is regenerated by evaluate_models."""
    summary, _, _ = evaluation
    committed = pd.read_csv(RESULTS_DIR / "model_performance.csv")
    pd.testing.assert_frame_equal(summary.reset_index(drop=True), committed, rtol=1e-6, atol=1e-6)


def test_quadratic_check_uses_center_observations():
    dataset = load_dataset()
    check = quadratic_insample_check(dataset)
    center = (dataset[["ph_coded", "temperature_coded", "agitation_coded", "time_coded"]] == 0).all(
        axis=1
    )
    center_mean = dataset.loc[center, TARGET_COLUMN].mean()
    assert np.isclose(check["center_observation_mean_g_l"], center_mean)
    assert check["paper_equation_9_intercept_g_l"] == 1.92
